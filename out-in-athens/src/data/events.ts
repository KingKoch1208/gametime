function startOfDay(d: Date): Date {
  const x = new Date(d);
  x.setHours(0, 0, 0, 0);
  return x;
}

function resolveWhen(w: When, now: Date): { start: Date; end: Date } {
  if ('rel' in w) {
    const start = new Date(now.getTime() + w.rel * 60_000);
    start.setSeconds(0, 0);
    // Round to the nearest quarter hour so times look real.
    start.setMinutes(Math.round(start.getMinutes() / 15) * 15);
    return { start, end: new Date(start.getTime() + w.mins * 60_000) };
  }
  const base = startOfDay(now);
  let dayOffset: number;
  if ('day' in w) {
    dayOffset = w.day;
  } else {
    const toSat = (6 - base.getDay() + 7) % 7;
    dayOffset = toSat + w.sat * 7;
  }
  const start = new Date(base);
  start.setDate(base.getDate() + dayOffset);
  start.setHours(w.h, w.m ?? 0, 0, 0);
  return { start, end: new Date(start.getTime() + w.hrs * 3_600_000) };
}

// Small deterministic hash so counts look organic but stay stable across reloads.
function seeded(id: string, min: number, max: number): number {
  let h = 0;
  for (let i = 0; i < id.length; i++) h = (h * 31 + id.charCodeAt(i)) >>> 0;
  return min + (h % (max - min + 1));
}

export function buildEvents(now: Date): AthensEvent[] {
  return SEEDS.map((s) => {
    const { when, v, ...rest } = s;
    const venue = V[v];
    const { start, end } = resolveWhen(when, now);
    const interested = s.interested ?? seeded(s.id, 12, 340);
    return {
      ...rest,
      start,
      end,
      venue: venue.name,
      coords: venue.coords,
      placeId: venue.placeId,
      interested,
      going: s.going ?? Math.round(interested * 0.4),
      friendsGoing: s.friendsGoing ?? [],
      indoor: s.indoor ?? true,
      soberFriendly: s.soberFriendly ?? !(s.access === '21+'),
      accessibleVenue: s.accessibleVenue ?? true,
      petFriendly: s.petFriendly ?? false,
    } as AthensEvent;
  });
}
